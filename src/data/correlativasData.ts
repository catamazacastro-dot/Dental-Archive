export const MATERIAS_STORAGE_KEY = 'dental_archive_materias_v1';
export const MATERIAS_DELETED_STORAGE_KEY = 'dental_archive_materias_deleted_v3';

export function loadDeletedMateriaIds(): string[] {
  try {
    const raw = localStorage.getItem(MATERIAS_DELETED_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed)) return parsed.filter((x): x is string => typeof x === 'string');
    }
  } catch {
    // Ignore storage errors
  }
  return [];
}

