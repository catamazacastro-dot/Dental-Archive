const IGNORED_LEGACY_IDS = new Set(['pre-op', 'orto-1', 'orto-2']);

export function loadMaterias(): MateriaPlan[] {
  const deletedSet = new Set(loadDeletedMateriaIds());
  const activeInitial = INITIAL_MATERIAS_PLAN.filter((m) => !deletedSet.has(m.id));
  try {
    const raw = localStorage.getItem(MATERIAS_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as MateriaPlan[];
      if (Array.isArray(parsed) && parsed.length > 0) {
        const savedById = new Map<string, MateriaPlan>();
        parsed.forEach((item) => {
          const mappedId = LEGACY_TO_UNLP_ID[item.id] || item.id;
          savedById.set(mappedId, item);
        });
        const initialIds = new Set(INITIAL_MATERIAS_PLAN.map((m) => m.id));
        const merged = activeInitial.map((base) => {
          const saved = savedById.get(base.id);
          return saved ? { ...base, estado: saved.estado } : base;
        });
        const customMaterias = parsed.filter(
          (item) =>
            !initialIds.has(item.id) &&
            !LEGACY_TO_UNLP_ID[item.id] &&
            !IGNORED_LEGACY_IDS.has(item.id) &&
            !deletedSet.has(item.id)
        );
        return [...merged, ...customMaterias];
      }
    }
  } catch {
    // Fallback to initial curriculum
  }
  return activeInitial;
}

